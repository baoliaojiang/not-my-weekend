/**
 * 把正文里的 emoji 换成 [xx] 形式的短标签。
 * 代理对、ZWJ 序列、变体选择符都要整体替换，不能只换掉半个字符——
 * 否则会留下半个代理对，JSON 序列化后接口直接报 400。
 */
export function stripEmojiForAPI(text) {
  const s = String(text == null ? '' : text);
  if (!s) return s;
  EMO_RE.lastIndex = 0;
  return s.split(EMO_RE).map((part, i) => {
    if (i % 2 !== 1) return part;
    return EMO_TEXT[part] || '[表情]';
  }).join('');
}

function esc(s) {
  return String(s)
    .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}
