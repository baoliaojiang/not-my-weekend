import puppeteer from 'file:///C:/Users/12821/.workbuddy/binaries/node/workspace/node_modules/puppeteer-core/lib/puppeteer/puppeteer-core.js';
const b = await puppeteer.launch({executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless:'new', args:['--no-sandbox']});
const p = await b.newPage();
p.on('pageerror', e=>console.log('PAGEERROR', e.message, '\n', e.stack?.split('\n').slice(0,4).join('\n')));
p.on('console', m=>{ if(m.type()==='error') console.log('CONSOLE_ERR', m.text()); });
await p.goto('http://127.0.0.1:5199/index.html',{waitUntil:'networkidle2'});
await new Promise(r=>setTimeout(r,600));
await p.evaluate(()=>document.querySelector('[data-act="new"]').click());
await new Promise(r=>setTimeout(r,300));
await p.evaluate(()=>document.querySelector('#disclaimerOk').click());
await new Promise(r=>setTimeout(r,1500));
console.log('disclaimer hidden', await p.evaluate(()=>document.querySelector('#disclaimer').hidden));
console.log('game hidden', await p.evaluate(()=>document.querySelector('#game').hidden));
console.log('title hidden', await p.evaluate(()=>document.querySelector('#titleScreen').hidden));
console.log('chapter text', await p.evaluate(()=>document.querySelector('#hudChapter').textContent));
console.log('bg image', await p.evaluate(()=>getComputedStyle(document.querySelector('#bgA')).backgroundImage.slice(0,80)));
console.log('dialogue hidden', await p.evaluate(()=>document.querySelector('#dialogue').hidden));
console.log('dlg text', await p.evaluate(()=>document.querySelector('#dlgText').textContent));
console.log('font used', await p.evaluate(()=>getComputedStyle(document.querySelector('#dlgText')).fontFamily));
console.log('font loaded?', await p.evaluate(()=>document.fonts.check('16px MiSans')));
await p.screenshot({path:'D:/workbuddy/2026-10-23-16-33-10/tools/shots/dbg-start.png'});
await b.close();
